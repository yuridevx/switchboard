// План выкладки: какие части выкладывать и в каком порядке. Чистая функция от отпечатков дерева и флота.

/** Порядок выкладки: платформа, службы со страницей, машины. */
export const PARTS = ["platform", "services", "machines"];

/** Части, чей отпечаток в дереве не совпал с тем, что стоит на флоте, — в порядке выкладки. Совпал — часть не трогают. */
export const plan = (tree, fleet) => PARTS.filter((part) => tree[part] !== fleet[part]);

/** Номер новой сборки машин: последний в каталоге флота плюс один. */
export const nextBuild = (builds) => Math.max(0, ...builds.map((b) => b.build)) + 1;
