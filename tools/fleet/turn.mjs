// Сценарий хода — одна форма просьбы к модели в живых проверках: пронумерованные шаги, каждый — вызов инструмента или ответ текстом.
// Настоящая модель исполняет его как просьбу; поддельная модель коробки (tools/box/model.mjs) разбирает его тем же файлом — формы в двух местах нет.
//   turn(tool("Bash", { command: "echo 1" }), say("готово"))
// Подстановки в тексте ответа: {итог N} — что вернул инструмент на шаге N; {прошлый итог} — что вернул последний вызов инструмента до этих шагов;
// {вызовов T} — сколько раз инструмент T вызван в разговоре до этих шагов.

const HEAD = "Выполни шаги по порядку. Кроме них ничего не делай и не пиши.";
const NOTES = [
  [/\{итог \d+\}/, "В тексте ответа вместо {итог N} поставь то, что вернул инструмент на шаге N."],
  [/\{прошлый итог\}/, "Вместо {прошлый итог} поставь то, что вернул твой последний вызов инструмента до этих шагов; такого не было — слово «нет»."],
  [/\{вызовов \w+\}/, "Вместо {вызовов T} поставь числом, сколько раз ты вызывал инструмент T в этом разговоре до этих шагов."],
];

/** Шаг: вызвать инструмент с точными полями. Имя — как его видит модель (у сервера флота — mcp__fleet__<имя>). */
export const tool = (name, fields = {}) => ({ tool: name, fields });
/** Шаг: ответить текстом. after — чего дождаться перед ответом: «придёт уведомление о конце фоновой команды». Ответ заканчивает ход. */
export const say = (text, after) => ({ say: text, ...(after ? { after } : {}) });

/** Текст просьбы по шагам. */
export function turn(...steps) {
  if (steps.some((s) => /[\r\n]/.test(s.say ?? ""))) throw new Error("ответ шага — одной строкой");
  const lines = steps.map((s, i) => `${i + 1}. ${"tool" in s ? `Вызови инструмент ${s.tool} с полями: ${JSON.stringify(s.fields)}` : `${s.after ? `Когда ${s.after}, ответь` : "Ответь"} текстом: ${s.say}`}`);
  const text = steps.map((s) => s.say ?? "").join("\n");
  return [HEAD, ...NOTES.filter(([re]) => re.test(text)).map(([, note]) => note), ...lines].join("\n");
}

const STEP = /^\d+\. (?:Вызови инструмент (\S+) с полями: (.*)|(?:Когда [^,]+, ответь|Ответь) текстом: (.*))$/;
/** Шаги из текста, в котором есть сценарий; сценария нет — null. Текст вокруг сценария не мешает: его добавляют обёртки сообщений. */
export function parse(text) {
  // первый заголовок — свой: сценарий внутри полей шага (задача другой сессии) идёт позже и остаётся строкой
  const at = text.indexOf(HEAD);
  if (at < 0) return null;
  const steps = [];
  for (const line of text.slice(at + HEAD.length).split("\n")) {
    const m = STEP.exec(line.trim());
    if (m) steps.push(m[1] ? tool(m[1], JSON.parse(m[2])) : say(m[3]));
    else if (steps.length) break;
  }
  return steps;
}
