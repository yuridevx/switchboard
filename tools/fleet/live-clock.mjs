// Живая проверка часов флота: node tools/fleet/live-clock.mjs <флот> <устройство>
// Сверка картины (машина без связи, сессия со сбоем) стоит правилом часов флота: его заводит первое число любой машины.
// Когда сверка шла последний раз, говорит сводка здоровья. Проверка читает этот момент и ждёт, пока он уйдёт вперёд:
// двигает его только срабатывание правила — будильник сработал сам.
import { check } from "./harness.mjs";

await check(async (t) => {
  /** Момент последней сверки картины. Сводка здоровья его только читает — из записей наблюдения; записей часов и их будильника она не касается. */
  const watched = async () => (await t.must("obs.health", {})).watched;
  let was;
  await t.step("сверка картины идёт по часам флота", async () => {
    // машины шлют числа раз в минуту: правило появляется не позже чем через минуту после выкладки, первая сверка — ещё через минуту
    was = await t.wait("первая сверка картины", watched, () => "сверки не было: ни одна машина не прислала чисел");
    return `последняя — ${Math.round((Date.now() - was) / 1000)} с назад`;
  });
  await t.step("срок пришёл без запроса: сверка прошла снова", async () => {
    // срок правила — минута: время здесь и есть свойство. Ждём факт — момент сверки ушёл вперёд, — а не «срок и запас»
    const now = await t.wait("следующая сверка картины", async () => {
      const at = await watched();
      return at > was && at;
    }, () => "момент сверки прежний");
    return `момент сверки ушёл вперёд на ${Math.round((now - was) / 1000)} с`;
  });
});
